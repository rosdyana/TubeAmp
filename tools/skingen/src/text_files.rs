//! The text entries of the skin: `VISCOLOR.TXT`, `PLEDIT.TXT` and `README.txt`.

use crate::paint::{hex, ramp, Rgb};
use crate::theme::crimson;
use std::fmt::Write;

/// Bar gradient for the spectrum (index 2 = top, red; index 17 = bottom, green).
const BAR_STOPS: [(f32, Rgb); 4] = [
    (0.0, hex(0xFF2A1A)),
    (0.33, hex(0xFF8A1A)),
    (0.66, hex(0xFFE01A)),
    (1.0, hex(0x1EE65A)),
];

/// `VISCOLOR.TXT`: 24 `r,g,b` lines.
///
/// 0 background, 1 grid dots, 2–17 bar gradient, 18–22 oscilloscope greens,
/// 23 peak.
pub fn viscolor() -> String {
    if crimson() {
        return crimson_viscolor();
    }
    let mut colours: Vec<Rgb> = vec![hex(0x05070A), hex(0x16241C)];
    colours.extend((0..16).map(|i| ramp(i as f32 / 15.0, &BAR_STOPS)));
    colours.extend([
        hex(0x1EE65A),
        hex(0x19C84B),
        hex(0x14AA3F),
        hex(0x0F8A33),
        hex(0x0A6B28),
        hex(0xE8F4EC),
    ]);
    assert_eq!(colours.len(), 24, "VISCOLOR.TXT needs exactly 24 colours");

    let mut out = String::from("// TubeAmp Classic visualiser colours (original artwork)\n");
    for [r, g, b] in colours {
        let _ = writeln!(out, "{r},{g},{b}");
    }
    out
}

/// Crimson Edge visualiser: black background, dark red dots, a red → orange → white-hot bar
/// gradient, red oscilloscope tones, and a white-hot peak.
fn crimson_viscolor() -> String {
    const CRIMSON_BARS: [(f32, Rgb); 3] = [
        (0.0, hex(0xE8102E)),
        (0.5, hex(0xFF7A1A)),
        (1.0, hex(0xFFF4F0)),
    ];
    let mut colours: Vec<Rgb> = vec![hex(0x0B0B0E), hex(0x2A0509)];
    colours.extend((0..16).map(|i| ramp(i as f32 / 15.0, &CRIMSON_BARS)));
    colours.extend([
        hex(0xFF3B4E),
        hex(0xE8102E),
        hex(0xC00D26),
        hex(0x9A0A1E),
        hex(0x7A0716),
        hex(0xFFF4F0),
    ]);
    let mut out = String::from("// Crimson Edge visualiser colours (original artwork)\n");
    for [r, g, b] in colours {
        let _ = writeln!(out, "{r},{g},{b}");
    }
    out
}

/// `PLEDIT.TXT`: playlist editor colours and font.
pub fn pledit() -> String {
    if crimson() {
        return "[Text]\n\
             Normal=#E8E8EC\n\
             Current=#FF3B4E\n\
             NormalBG=#0B0B0E\n\
             SelectedBG=#4A0612\n\
             Font=Arial\n"
            .to_string();
    }
    "[Text]\n\
     Normal=#1EE65A\n\
     Current=#FFFFFF\n\
     NormalBG=#05070A\n\
     SelectedBG=#1E3A8A\n\
     Font=Arial\n"
        .to_string()
}

/// `README.txt`: credit and licence line for the generated skin.
pub fn readme() -> String {
    if crimson() {
        return "Crimson Edge, original artwork; not affiliated with any brand.\n".to_string();
    }
    "TubeAmp Classic\n\
     \n\
     Original artwork generated by tools/skingen; © TubeAmp authors; license: same as the TubeAmp repository\n\
     \n\
     Regenerate with: cargo run -p tubeamp-skingen -- assets/default-skin\n"
        .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn viscolor_has_24_parseable_lines() {
        let text = viscolor();
        let triplets: Vec<&str> = text.lines().filter(|l| !l.starts_with("//")).collect();
        assert_eq!(triplets.len(), 24);
        for line in triplets {
            let parts: Vec<u8> = line.split(',').map(|p| p.parse().expect("u8")).collect();
            assert_eq!(parts.len(), 3);
        }
    }
}
